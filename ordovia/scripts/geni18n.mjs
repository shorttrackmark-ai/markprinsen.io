// Bundles i18n/nl-*.json (English text -> Dutch text) into public/js/nl.js. Run by npm test and npm run deploy.
import fs from 'node:fs';
const dir = new URL('../i18n/', import.meta.url);
const all = {};
for (const f of fs.readdirSync(dir).filter(x => /^nl-.*\.json$/.test(x)).sort()) {
  const part = JSON.parse(fs.readFileSync(new URL(f, dir), 'utf8'));
  for (const [k, v] of Object.entries(part)) all[k] = v;
}
fs.writeFileSync(new URL('../public/js/nl.js', import.meta.url), '/* GENERATED by scripts/geni18n.mjs from i18n/nl-*.json – do not edit. */\nwindow.FB = window.FB || {};\nFB.i18n.add(' + JSON.stringify(all) + ');\n');
console.log('Dutch entries:', Object.keys(all).length);
// the same dictionary for the Worker (templates are translated on the server before they are stored)
fs.writeFileSync(new URL('../src/nl.gen.js', import.meta.url), '// GENERATED by scripts/geni18n.mjs from i18n/nl-*.json – do not edit.\nexport const NL = ' + JSON.stringify(all) + ';\n');
